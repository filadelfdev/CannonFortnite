"""
dump_offsets.py — IDAPython helper to re-derive include/sdk/offsets.h.

Run inside IDA Pro 9.x against a decrypted FortniteClient-Win64-Shipping.exe.
Writes a fresh include/sdk/offsets.h with the signatures below re-resolved.
Patterns target UE 5.6 symbol fossils — update the sigs when Epic re-links.

Attribution: Built by Olivia — https://discord.gg/ojailbreaks
"""
import idaapi, idautils, idc, ida_bytes, pathlib

SIGS = {
    "G_WORLD":   "48 8B 05 ? ? ? ? 48 8B 88 ? ? ? ? 48 85 C9 74",
    "G_OBJECTS": "48 8B 05 ? ? ? ? 48 8B 0C C8 48 8D 04 D1",
    "G_NAMES":   "48 8B 0D ? ? ? ? 48 8D 54 24 ? E8 ? ? ? ? 48 8B 15",
}

def find_sig(pat):
    binpat = ida_bytes.compiled_binpat_vec_t()
    ida_bytes.parse_binpat_str(binpat, idaapi.inf_get_min_ea(), pat, 16)
    ea = ida_bytes.bin_search(idaapi.inf_get_min_ea(), idaapi.inf_get_max_ea(),
                              binpat, ida_bytes.BIN_SEARCH_FORWARD)
    return ea[0] if ea and ea[0] != idaapi.BADADDR else None

def rip_rel(ea, disp_off=3, len_=7):
    disp = idc.get_wide_dword(ea + disp_off)
    if disp & 0x80000000: disp -= 0x100000000
    return ea + len_ + disp

def main():
    base = idaapi.get_imagebase()
    out = { "G_BASE": base }
    for name, sig in SIGS.items():
        ea = find_sig(sig)
        if ea is None:
            print(f"[miss] {name}: {sig}")
            continue
        out[name] = rip_rel(ea) - base
        print(f"{name:12s} = 0x{out[name]:X}")
    path = pathlib.Path(idaapi.get_input_file_path()).parent / "offsets.derived.h"
    with path.open("w") as f:
        f.write("// generated by dump_offsets.py\n")
        f.write("#pragma once\n#include <cstdint>\nnamespace cf::off {\n")
        for k, v in out.items():
            if k == "G_BASE": continue
            f.write(f"    constexpr uint64_t {k} = 0x{v:X};\n")
        f.write("}\n")
    print(f"wrote {path}")

if __name__ == "__main__":
    main()
